fn take_ownership(text: String ) { //тут можно указать &String и при вызове take_ownership() нужно указывать внутри обязательно взаимстование & чтобы удачно передать данные в ином случае код не скомпилируеться
    println!("Функция забрала строку: {}", text)
} // здесь строка уничтожается

fn test(text: &str) {
    take_ownership(text.to_string());
}

