/*Данные можно клонировать благодаря .clone() например take_ownership(original.clone()); таким образом сделаем слепок данных из переменной благодаря этому мы можем не взаимствовать данные, но это слишком дорогое удовольствие для памяти */
/*функция to_string() подобие clone() превращает текст в String не в строковый срез создавая копию в памяти */